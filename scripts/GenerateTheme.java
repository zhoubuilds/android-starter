import com.google.android.material.color.utilities.DynamicScheme;
import com.google.android.material.color.utilities.Hct;
import com.google.android.material.color.utilities.SchemeTonalSpot;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.charset.StandardCharsets;
import java.util.Locale;
import java.util.Properties;
import javax.xml.parsers.DocumentBuilderFactory;
import javax.xml.transform.OutputKeys;
import javax.xml.transform.Transformer;
import javax.xml.transform.TransformerFactory;
import javax.xml.transform.dom.DOMSource;
import javax.xml.transform.stream.StreamResult;
import org.w3c.dom.Document;
import org.w3c.dom.Element;

/**
 * 使用工程锁定的 Material Color Utilities 生成应用的固定浅深配色.
 *
 * @author whisper
 * @since 2026/09/11
 */
class GenerateTheme {
    private static final String[] ROLES = {
        "Primary", "OnPrimary", "PrimaryContainer", "OnPrimaryContainer", "InversePrimary",
        "Secondary", "OnSecondary", "SecondaryContainer", "OnSecondaryContainer",
        "Tertiary", "OnTertiary", "TertiaryContainer", "OnTertiaryContainer",
        "Background", "OnBackground", "Surface", "OnSurface", "SurfaceVariant", "OnSurfaceVariant",
        "SurfaceDim", "SurfaceBright", "SurfaceContainerLowest", "SurfaceContainerLow",
        "SurfaceContainer", "SurfaceContainerHigh", "SurfaceContainerHighest",
        "InverseSurface", "InverseOnSurface", "Outline", "OutlineVariant",
        "Error", "OnError", "ErrorContainer", "OnErrorContainer",
        "PrimaryFixed", "PrimaryFixedDim", "OnPrimaryFixed", "OnPrimaryFixedVariant",
        "SecondaryFixed", "SecondaryFixedDim", "OnSecondaryFixed", "OnSecondaryFixedVariant",
        "TertiaryFixed", "TertiaryFixedDim", "OnTertiaryFixed", "OnTertiaryFixedVariant",
        "SurfaceTint", "Scrim", "Shadow"
    };

    public static void main(String[] args) throws Exception {
        Path root = args.length == 0 ? Path.of("") : Path.of(args[0]);
        Properties config = new Properties();
        try (InputStream input = Files.newInputStream(root.resolve("design/brand/theme-seed.properties"))) {
            config.load(input);
        }
        if (!"SchemeTonalSpot".equals(config.getProperty("scheme"))) {
            throw new IllegalArgumentException("Only SchemeTonalSpot is supported.");
        }
        String seedHex = config.getProperty("seed");
        if (seedHex == null || !seedHex.matches("#[0-9A-Fa-f]{6}")) {
            throw new IllegalArgumentException("Seed must be a six-digit RGB hex color.");
        }
        int seed = 0xFF000000 | Integer.parseInt(seedHex.substring(1), 16);
        double contrast = Double.parseDouble(config.getProperty("contrast"));
        if (!Double.isFinite(contrast) || contrast < -1 || contrast > 1) {
            throw new IllegalArgumentException("Contrast must be between -1 and 1.");
        }
        for (boolean dark : new boolean[]{false, true}) {
            DynamicScheme scheme = new SchemeTonalSpot(Hct.fromInt(seed), dark, contrast);
            DynamicScheme inverse = new SchemeTonalSpot(Hct.fromInt(seed), !dark, contrast);
            Document document = DocumentBuilderFactory.newInstance().newDocumentBuilder().newDocument();
            document.setXmlStandalone(true);
            Element resources = document.createElement("resources");
            document.appendChild(resources);
            resources.appendChild(document.createComment(
                " Generated by scripts/GenerateTheme.java; edit design/brand/theme-seed.properties. "
            ));
            if (!dark) {
                addColor(document, resources, "brand_seed", seed);
            }
            for (String role : ROLES) {
                int color = (int) DynamicScheme.class.getMethod("get" + role).invoke(scheme);
                String name = role.replaceAll("([a-z])([A-Z])", "$1_$2").toLowerCase(Locale.ROOT);
                addColor(document, resources, name, color);
            }
            addColor(document, resources, "text_inverse_primary", inverse.getOnSurface());
            addColor(document, resources, "text_inverse_secondary", inverse.getOnSurfaceVariant());
            addColor(document, resources, "text_selection", dark ? scheme.getPrimary() : scheme.getOnPrimaryContainer());
            addColor(document, resources, "text_selection_inverse", dark ? inverse.getOnPrimaryContainer() : inverse.getPrimary());
            Path output = root.resolve("foundation/src/main/res")
                .resolve(dark ? "values-night" : "values").resolve("foundation_colors.xml");
            Files.createDirectories(output.getParent());
            Transformer transformer = TransformerFactory.newInstance().newTransformer();
            transformer.setOutputProperty(OutputKeys.ENCODING, "utf-8");
            transformer.setOutputProperty(OutputKeys.INDENT, "yes");
            transformer.setOutputProperty(OutputKeys.OMIT_XML_DECLARATION, "yes");
            transformer.setOutputProperty("{http://xml.apache.org/xslt}indent-amount", "4");
            try (var stream = Files.newOutputStream(output)) {
                stream.write("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n".getBytes(StandardCharsets.UTF_8));
                transformer.transform(new DOMSource(document), new StreamResult(stream));
            }
            System.out.println("Generated " + output + " (" + ROLES.length + " roles + 4 text colors)");
        }
    }

    private static void addColor(Document document, Element resources, String name, int argb) {
        Element color = document.createElement("color");
        color.setAttribute("name", "foundation_" + name);
        color.setTextContent(String.format(Locale.ROOT, "#%06X", argb & 0xFFFFFF));
        resources.appendChild(color);
    }
}
